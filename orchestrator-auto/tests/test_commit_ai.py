class TestBuildPrompt:
    """Test prompt building function."""

    def test_build_prompt_basic(self):
        """Test basic prompt building."""
        diff = "+def hello(): pass"
        stats = {"files_changed": 1, "insertions": 1, "deletions": 0}
        feature_hint = "Add greeting function"

        prompt = _build_prompt(diff, stats, feature_hint)

        assert "Add greeting function" in prompt
        assert "1 files changed" in prompt
        assert "1 insertions" in prompt
        assert "0 deletions" in prompt
        assert "+def hello(): pass" in prompt

    def test_build_prompt_truncates_large_diff(self):
        """Test that large diffs are truncated in prompt."""
        large_diff = "x" * 10000
        stats = {"files_changed": 1, "insertions": 100, "deletions": 0}

        prompt = _build_prompt(large_diff, stats, "")

        # Should be truncated to 6000 chars for diff portion
        assert len(prompt) < 10000

    def test_build_prompt_empty_feature_hint(self):
        """Test prompt with empty feature hint."""
        diff = "+code"
        stats = {"files_changed": 1, "insertions": 1, "deletions": 0}

        prompt = _build_prompt(diff, stats, "")

        assert "Code changes" in prompt  # Default hint

    def test_build_prompt_missing_stats(self):
        """Test prompt with missing stats keys."""
        diff = "+code"
        stats = {}  # Empty stats

        prompt = _build_prompt(diff, stats, "Test")

        assert "0 files changed" in prompt
        assert "0 insertions" in prompt
        assert "0 deletions" in prompt


