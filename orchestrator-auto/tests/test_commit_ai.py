class TestSubjectLineTruncation:
    """Test 72-char subject line enforcement."""

    def test_short_subject_unchanged(self):
        """Test that short subjects are not modified."""
        message = "feat: add feature"
        result = _clean_and_validate(message)
        assert result == "feat: add feature"

    def test_exactly_72_chars_unchanged(self):
        """Test that exactly 72-char subjects are not modified."""
        # Create a subject that's exactly 72 chars
        subject = "feat: " + "x" * 66  # 6 + 66 = 72
        assert len(subject) == 72
        result = _clean_and_validate(subject)
        assert result == subject

    def test_long_subject_truncated(self):
        """Test that long subjects are truncated to 72 chars."""
        # Create a subject that's too long
        subject = "feat: " + "x" * 100  # 106 chars total
        result = _clean_and_validate(subject)
        assert result is not None
        assert len(result) <= MAX_SUBJECT_LENGTH

    def test_truncates_at_word_boundary(self):
        """Test that truncation prefers word boundaries."""
        subject = "feat: add a really long feature description that exceeds the maximum allowed length for commit subjects"
        result = _clean_and_validate(subject)
        assert result is not None
        assert len(result) <= MAX_SUBJECT_LENGTH
        # Should end at a word boundary (space before last word in original)
        # The truncated result should be a prefix of the original that ends at a word break
        assert subject.startswith(result)
        # If truncated, the next char in original should be a space (word boundary)
        if len(result) < len(subject):
            assert subject[len(result)] == " ", f"Truncation split mid-word: '{result}'"

    def test_long_subject_with_body_preserved(self):
        """Test that body is preserved when subject is truncated."""
        message = "feat: " + "x" * 100 + "\n\n- bullet point"
        result = _clean_and_validate(message)
        assert result is not None
        lines = result.split("\n")
        assert len(lines[0]) <= MAX_SUBJECT_LENGTH
        assert "bullet point" in result


class TestGenerateSmartCommitMessageAsync:
    """Test async commit message generation with mocked SDK."""

    @pytest.fixture
    def mock_text_block(self):
        """Create a mock TextBlock."""
        block = Mock()
        block.text = "feat: add new feature\n\n- Add feature implementation"
        return block

    @pytest.fixture
    def mock_assistant_message(self, mock_text_block):
        """Create a mock AssistantMessage."""
        message = Mock(spec=["content"])
        message.content = [mock_text_block]
        # Make isinstance check work
        message.__class__ = type("AssistantMessage", (), {})
        return message

    @pytest.fixture
    def mock_result_message(self):
        """Create a mock ResultMessage."""
        message = Mock()
        message.__class__ = type("ResultMessage", (), {})
        return message

    @pytest.mark.asyncio
    async def test_generates_feat_message(self):
        """Test generation of feat commit message."""
        diff = "+def new_feature(): pass"
        stats = {"files_changed": 1, "insertions": 1, "deletions": 0}

        with patch("orchestrator_auto.commit_ai.ClaudeSDKClient") as mock_client_class:
            # Create mock client
            mock_client = AsyncMock()

            # Mock the async context manager
            mock_client_class.return_value.__aenter__ = AsyncMock(return_value=mock_client)
            mock_client_class.return_value.__aexit__ = AsyncMock(return_value=None)

            # Create mock messages
            mock_text = Mock()
            mock_text.text = "feat: add new feature\n\n- Add feature implementation"

            mock_assistant = Mock()
            mock_assistant.content = [mock_text]

            mock_result = Mock()

            # Setup receive_messages to yield messages
            async def mock_receive():
                # Patch isinstance checks
                with patch("orchestrator_auto.commit_ai.AssistantMessage", type(mock_assistant)):
                    with patch("orchestrator_auto.commit_ai.TextBlock", type(mock_text)):
                        with patch("orchestrator_auto.commit_ai.ResultMessage", type(mock_result)):
                            yield mock_assistant
                            yield mock_result

            mock_client.receive_messages = mock_receive

            result = await generate_smart_commit_message_async(
                diff=diff,
                stats=stats,
                feature_hint="Add feature",
            )

        # Should return valid message or None (depending on mock setup)
        # The important thing is it doesn't crash
        assert result is None or isinstance(result, str)

    @pytest.mark.asyncio
    async def test_returns_none_on_empty_diff(self):
        """Test that empty diff returns None."""
        result = await generate_smart_commit_message_async(
            diff="",
            stats={"files_changed": 0, "insertions": 0, "deletions": 0},
        )
        assert result is None

    @pytest.mark.asyncio
    async def test_returns_none_on_timeout(self):
        """Test that timeout returns None."""
        with patch("orchestrator_auto.commit_ai.ClaudeSDKClient") as mock_client_class:
            # Make client hang
            async def slow_enter():
                await asyncio.sleep(100)
                return Mock()

            mock_client_class.return_value.__aenter__ = slow_enter

            result = await generate_smart_commit_message_async(
                diff="+code",
                stats={"files_changed": 1, "insertions": 1, "deletions": 0},
                timeout=1,  # 1 second timeout
            )

        assert result is None

    @pytest.mark.asyncio
    async def test_returns_none_on_exception(self):
        """Test that exceptions return None."""
        with patch("orchestrator_auto.commit_ai.ClaudeSDKClient") as mock_client_class:
            # Make client raise exception
            mock_client_class.return_value.__aenter__ = AsyncMock(
                side_effect=Exception("API Error")
            )

            result = await generate_smart_commit_message_async(
                diff="+code",
                stats={"files_changed": 1, "insertions": 1, "deletions": 0},
            )

        assert result is None


